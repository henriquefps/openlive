// Writes THIRD_PARTY_NOTICES at the repository root: the npm packages
// bundled into the web app and the API Worker, from `pnpm licenses list --prod`, with each
// package's license text from node_modules. The helper has its own, generated at build time
// (packaging/linux/gen-third-party-notices.sh). Run after `pnpm install`.
//
//   node scripts/third-party-notices.mjs           # rewrite THIRD_PARTY_NOTICES
//   node scripts/third-party-notices.mjs --check   # exit 1 if it is out of date (CI)
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'THIRD_PARTY_NOTICES';

// Production dependencies of the two deployed apps (workspace packages are ours).
const listed = JSON.parse(
  execFileSync(
    'pnpm',
    [
      'licenses',
      'list',
      '--prod',
      '--json',
      '--filter',
      '@openlive/web',
      '--filter',
      '@openlive/api',
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ),
);
const packages = new Map();
for (const [license, entries] of Object.entries(listed)) {
  for (const entry of entries) {
    if (entry.name.startsWith('@openlive/')) continue;
    entry.versions.forEach((version, i) => {
      packages.set(`${entry.name}@${version}`, {
        name: entry.name,
        version,
        license,
        dir: entry.paths[i],
      });
    });
  }
}

// Build-time packages whose CSS ends up in the web bundle although they are devDependencies.
for (const name of ['tailwindcss', 'tw-animate-css']) {
  const dir = realpathSync(join('apps/web/node_modules', name));
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  packages.set(`${name}@${pkg.version}`, { name, version: pkg.version, license: pkg.license, dir });
}

// Code-point order, so the file is the same whatever the machine's locale.
const sorted = [...packages.entries()].sort(([a], [b]) => (a < b ? -1 : 1)).map(([, p]) => p);

function licenseText(dir) {
  const files = readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f))
    .sort();
  return files.map((f) => readFileSync(join(dir, f), 'utf8').trim()).join('\n\n');
}

const lines = [
  'Third-party notices for the Openlive web app and API',
  '====================================================',
  '',
  'Openlive is licensed under the AGPL-3.0 (LICENSE). The web app (apps/web) and the API Worker',
  '(apps/api) bundle the npm packages below, each under its own license, reproduced after the',
  'list. The helper ships its own THIRD_PARTY_NOTICES with its binaries',
  '(packaging/linux/gen-third-party-notices.sh).',
  '',
  'Generated by scripts/third-party-notices.mjs from `pnpm licenses list --prod`; do not edit.',
  '',
  'Packages',
  '--------',
  '',
  ...sorted.map((p) => `- ${p.name} ${p.version} (${p.license})`),
  '',
  'License texts',
  '-------------',
];
for (const p of sorted) {
  const text = licenseText(p.dir);
  lines.push('', `### ${p.name} ${p.version} (${p.license})`, '');
  lines.push(text || `(no license file in the package; its package.json declares ${p.license})`);
}
const output = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing counts as out of date
  }
  if (current !== output) {
    console.error(`${OUT} is out of date: run pnpm notices and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${sorted.length} packages).`);
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT} (${sorted.length} packages).`);
}
