/* eslint-disable @typescript-eslint/no-require-imports -- an Expo config plugin is CommonJS */
// Expo config plugin: the WebRTC audio device plays as MEDIA, not as a phone call.
//
// react-native-webrtc builds its JavaAudioDeviceModule with USAGE_VOICE_COMMUNICATION unless
// WebRTCModuleOptions.audioDeviceModule is set before the first WebRTCModule is created. This
// plugin writes OpenliveAudioPlayout.kt into the app and calls it from MainApplication.onCreate
// (prebuild regenerates android/, so nothing is edited by hand).
const fs = require('node:fs');
const path = require('node:path');
const { withDangerousMod, withMainApplication } = require('expo/config-plugins');

const MARK = 'OpenliveAudioPlayout.install(this)';

const kotlin = (pkg) => `// SPDX-License-Identifier: AGPL-3.0-only
package ${pkg}

import android.content.Context
import android.media.AudioAttributes
import com.oney.WebRTCModule.WebRTCModuleOptions
import org.webrtc.audio.JavaAudioDeviceModule

// Generated by plugins/with-openlive-audio.js. Watching plays as media (volume keys, Bluetooth
// A2DP, the speaker); voice switches the AudioManager mode, not this device (see OpenliveAudio).
object OpenliveAudioPlayout {
  fun install(context: Context) {
    val options = WebRTCModuleOptions.getInstance()
    if (options.audioDeviceModule != null) return
    options.audioDeviceModule =
      JavaAudioDeviceModule.builder(context)
        .setAudioAttributes(
          AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_MEDIA)
            .setContentType(AudioAttributes.CONTENT_TYPE_MOVIE)
            .build()
        )
        .setEnableVolumeLogger(false)
        .createAudioDeviceModule()
  }
}
`;

function withOpenliveAudio(config) {
  const pkg = config.android?.package;
  if (!pkg) throw new Error('with-openlive-audio: android.package is required');

  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...pkg.split('.'),
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'OpenliveAudioPlayout.kt'), kotlin(pkg));
      return cfg;
    },
  ]);

  return withMainApplication(config, (cfg) => {
    const src = cfg.modResults.contents;
    if (!src.includes(MARK)) {
      const next = src.replace(/(super\.onCreate\(\)\n)/, `$1    ${MARK}\n`);
      if (next === src) throw new Error('with-openlive-audio: MainApplication has no onCreate');
      cfg.modResults.contents = next;
    }
    return cfg;
  });
}

module.exports = withOpenliveAudio;
